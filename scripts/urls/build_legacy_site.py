"""Build the static site for the OLD address, tsglab.github.io/mi_survey/, which forwards every
published page (and its #anchor) to the same page at the new address.

The output is the whole content of the TSGLAB/mi_survey repository (GitHub Pages, branch main, root):

    python3 scripts/urls/build_legacy_site.py --out ../mi_survey-redirect

Every URL in src/data/published-urls.json gets its own page (HTTP 200, canonical link to the new
URL, noindex); anything else is caught by 404.html. Old chapter URLs go straight to their stable
ids (src/data/redirects.json), without a second hop.
"""
from __future__ import annotations

import argparse
import html
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OLD = "/mi_survey/"
NEW = "https://tsglab.github.io/mechinterp-safety/"

PAGE = """<!doctype html>
<html lang="en-GB"><head><meta charset="utf-8">
<title>This site has moved</title>
<meta name="robots" content="noindex">
<link rel="canonical" href="{url}">
<script>location.replace({url_js} + location.hash);</script>
<meta http-equiv="refresh" content="0; url={url}">
</head><body><h1>This site has moved</h1>
<p>The interactive handbook is now at <a href="{url}">{url}</a>.</p></body></html>
"""

FALLBACK = """<!doctype html>
<html lang="en-GB"><head><meta charset="utf-8">
<title>This site has moved</title>
<meta name="robots" content="noindex">
<script>
  // Any other old path: same path at the new address.
  var p = location.pathname.indexOf({old_js}) === 0 ? location.pathname.slice({old_len}) : "";
  location.replace({new_js} + p + location.search + location.hash);
</script>
</head><body><h1>This site has moved</h1>
<p>The interactive handbook is now at <a href="{new}">{new}</a>.</p></body></html>
"""


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True, type=Path)
    out: Path = ap.parse_args().out
    pages = json.loads((ROOT / "src/data/published-urls.json").read_text())["pages"]
    moved = json.loads((ROOT / "src/data/redirects.json").read_text())["pages"]
    for path in pages:
        target = NEW + moved.get(path, path)
        d = out / path
        d.mkdir(parents=True, exist_ok=True)
        (d / "index.html").write_text(PAGE.format(url=html.escape(target), url_js=json.dumps(target)))
    (out / "404.html").write_text(FALLBACK.format(old_js=json.dumps(OLD), old_len=len(OLD),
                                                  new_js=json.dumps(NEW), new=NEW))
    (out / ".nojekyll").write_text("")
    (out / "README.md").write_text(
        "# Moved\n\nThe interactive handbook for *The State of Mechanistic Interpretability for AI Safety* "
        f"is now at {NEW}\n\nSource: https://github.com/TSGLAB/mechinterp-safety\n\n"
        "This repository only keeps old links to tsglab.github.io/mi_survey/ working. It is generated by "
        "`scripts/urls/build_legacy_site.py` in the source repository.\n")
    print(f"{len(pages)} redirect pages + 404 fallback -> {out}")


if __name__ == "__main__":
    main()
